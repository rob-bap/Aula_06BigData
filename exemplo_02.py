lista_dias = []
lista_meses = ["janeiro", "fevereiro", "março", "abril", "maio", "junho"]

print(lista_dias)
print(lista_meses)
print(type(lista_meses))

print(lista_meses[0])  # número definido entre "[]" mostra a várivel na posição dito 
print(lista_meses[3])  # terceiro começando do zero
print(lista_meses[-1])  # ultimo
print(lista_meses[1:4])  # fatiamento mostra as varaveis entre posições definidas
print(lista_meses[2:])